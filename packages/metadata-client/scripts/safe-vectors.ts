// Vectors of the Safe's formats for the phone (Kotlin must open what the web app sealed and seal what it
// opens): Argon2id → wrap key → master, the slot's two layers, padding, the Safe kit. The real Argon2
// parameters (64 MiB / 3 / 4), so the Kotlin test measures what the phone will spend.
// Run: npx tsx scripts/safe-vectors.ts (writes apps/android/core/ddn/src/test/resources/safe-vectors.json).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { toBase64 } from "@ddv4/processing";
import { accountKeyFromRaw, SAFE_ARGON2, newSafeHeader, openSafeMaster, safeArgon2, safeKitText, sealSafeSlot, openSafeHeader, openSafeState } from "../src/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "..", "apps", "android", "core", "ddn", "src", "test", "resources", "safe-vectors.json");
const bytes = (n: number, seed: number) => Uint8Array.from({ length: n }, (_, i) => (i * 29 + seed * 11 + 5) & 255);
const hex = (b: Uint8Array) => [...b].map((x) => x.toString(16).padStart(2, "0")).join("");

const ACCT = "acct-SAFESAFESAFESAFESAFE01";
const key = accountKeyFromRaw(bytes(32, 1));
const master = bytes(32, 2);
const password = "Zażółć gęślą jaźń 2026";
const salt = bytes(16, 3);
const header = await newSafeHeader(master, password, ACCT, SAFE_ARGON2, salt);
const argon = await safeArgon2(password, header.kdf);
if (hex(await openSafeMaster(header, password, ACCT)) !== hex(master)) throw new Error("self-check");
const state = { v: 1, nodes: [{ id: "n1", name: "paszport.jpg" }, { id: "n2", name: "Zdjęcia — prywatne" }] };
const revision = 7;
const blob = await sealSafeSlot({ key, accountId: ACCT, revision, header, master, state });
const opened = await openSafeHeader(key, ACCT, revision, blob);
if (JSON.stringify(await openSafeState(master, ACCT, revision, opened.sealedState)) !== JSON.stringify(state)) throw new Error("self-check 2");

const v = {
  note: "Generated by packages/metadata-client/scripts/safe-vectors.ts. Do not edit.",
  accountId: ACCT,
  accountKeyB64: key.rawB64,
  password,
  argon2: { kdf: header.kdf, outHex: hex(argon) },
  masterHex: hex(master),
  header,
  slot: { revision, blob, state },
  kit: safeKitText(ACCT, master),
  masterB64: toBase64(master),
};
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(v, null, 1) + "\n");
console.log(JSON.stringify({ out, blobChars: blob.length }));
