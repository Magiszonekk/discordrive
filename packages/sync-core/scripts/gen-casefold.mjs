#!/usr/bin/env node
// Generates src/casefold-table.ts: a frozen lowercase mapping used by nameKey().
//
// Why a table instead of String.prototype.toLowerCase(): the name key decides
// collisions (rule 2), so it is part of the replicated state machine. Every
// client must compute it identically. toLowerCase() depends on the Unicode
// version of the JS engine (Safari, Chrome, Node ship different ICU versions),
// so two clients could disagree on characters added in a newer Unicode
// release and their states would diverge. The table pins the mapping to one
// Unicode version. Changing it requires a new RULES_VERSION.
//
// Run with the Node version you want to pin (the header records the version).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

// Simple case folding approximated as lower(upper(c)) when the uppercase form
// is a single code point, otherwise lower(c). This folds Greek final sigma
// (ς -> σ), long s (ſ -> s), Kelvin sign etc. like Unicode simple folding, and
// keeps ß distinct from "ss" (as NTFS does).
function fold(s) {
  const upper = s.toUpperCase();
  if ([...upper].length === 1) {
    const l = upper.toLowerCase();
    if ([...l].length === 1) return l;
  }
  return s.toLowerCase();
}

const pairs = [];
const special = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  const lower = fold(s);
  if (lower === s) continue;
  const cps = [...lower].map((c) => c.codePointAt(0));
  if (cps.length === 1) pairs.push([cp, cps[0]]);
  else special.push([cp, cps]);
}

// Run-length encode: [start, count, stride, delta] where mapping(start + i*stride) = start + i*stride + delta
const runs = [];
let i = 0;
while (i < pairs.length) {
  const [cp, to] = pairs[i];
  const delta = to - cp;
  let stride = 0;
  let count = 1;
  if (i + 1 < pairs.length && pairs[i + 1][1] - pairs[i + 1][0] === delta) {
    stride = pairs[i + 1][0] - cp;
    if (stride === 1 || stride === 2) {
      count = 2;
      while (
        i + count < pairs.length &&
        pairs[i + count][0] === cp + count * stride &&
        pairs[i + count][1] - pairs[i + count][0] === delta
      ) {
        count++;
      }
    } else {
      stride = 0;
    }
  }
  runs.push(cp, count, stride || 1, delta);
  i += count;
}

const out = `// GENERATED by scripts/gen-casefold.mjs — do not edit by hand.
// Unicode ${process.versions.unicode} (ICU ${process.versions.icu}, Node ${process.versions.node}).
// ${pairs.length} single-code-point lowercase mappings in ${runs.length / 4} runs, ${special.length} multi-code-point.
// Part of RULES_VERSION 1: changing this table changes name keys and requires a rules version bump.

export const CASEFOLD_UNICODE_VERSION = ${JSON.stringify(process.versions.unicode)};

/** Flat runs: start, count, stride, delta. */
export const CASEFOLD_RUNS: readonly number[] = ${JSON.stringify(runs)};

/** Code points whose lowercase form is longer than one code point. */
export const CASEFOLD_SPECIAL: readonly (readonly [number, readonly number[]])[] = ${JSON.stringify(special)};
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "casefold-table.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${pairs.length} pairs, ${runs.length / 4} runs, ${special.length} special`);
