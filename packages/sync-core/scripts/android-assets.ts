// Assets of the Android app (apps/android/syncjs), generated from this package:
//  - src/main/assets/sync-core.js: the sync core as one script for the phone's JS engine
//    (IIFE, global `SyncCore`, ES2020, no imports, no Node or browser APIs);
//  - sync-vectors.txt (with --vectors <file>): random logs from the simulator (test/sim.ts) and the
//    SHA-256 of the canonical state Node gets from each; the phone's compatibility test must get the same.
//    Header line (JSON), then one line per log: "<sha256 hex> <log as JSON>".
// The bundle is committed, so building the app needs no Node; CI regenerates it and fails on a diff, so a
// rules change and the phone's copy of the rules land in one commit. The vectors are generated by the
// Android test build (Gradle task generateSyncVectors) and not committed; the test also checks that the
// bundle in the app is the one the vectors were made with.
//
// Usage: npx tsx scripts/android-assets.ts [--vectors <file> [--vectors-only]] [--cases 40] [--seed 7]
// (--vectors-only: do not rewrite the bundle in the app, only the vectors; what the Gradle task uses).

import fc from "fast-check";
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalState, initIndex, applyEntry, MemoryIndexStore, RULES_VERSION, type LogEntry } from "../src/index.js";
import { actionArb, newStats, runCase, lastLog } from "../test/sim.js";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const bundleFile = join(pkg, "..", "..", "apps", "android", "syncjs", "src", "main", "assets", "sync-core.js");
const arg = (name: string): string | undefined => {
  const i = process.argv.indexOf(`--${name}`);
  return i < 0 ? undefined : process.argv[i + 1];
};
const vectorsFile = arg("vectors");
const vectorsOnly = process.argv.includes("--vectors-only");
const cases = Number(arg("cases") ?? 40);
const seed = Number(arg("seed") ?? 7);

const bundle = await build({
  entryPoints: [join(pkg, "src", "index.ts")],
  bundle: true,
  platform: "neutral",
  format: "iife",
  globalName: "SyncCore",
  target: "es2020",
  minify: true,
  legalComments: "none",
  write: false,
});
const code = `// Generated by packages/sync-core/scripts/android-assets.ts. Do not edit.\n${bundle.outputFiles[0]!.text}`;

if (!vectorsOnly) {
  mkdirSync(dirname(bundleFile), { recursive: true });
  writeFileSync(bundleFile, code);
}
const sha = (s: string) => createHash("sha256").update(s, "utf8").digest("hex");
const summary: Record<string, unknown> = { bundleBytes: Buffer.byteLength(code), bundleSha256: sha(code), rulesVersion: RULES_VERSION };

if (vectorsFile) {
  const logs: LogEntry[][] = [];
  const stats = newStats();
  for (const actions of fc.sample(fc.array(actionArb, { minLength: 30, maxLength: 300, size: "max" }), { seed, numRuns: cases })) {
    runCase(actions, stats);
    logs.push(lastLog()!);
  }
  const t0 = performance.now();
  const hashes = logs.map((log) => {
    const st = initIndex(new MemoryIndexStore());
    for (const e of log) applyEntry(st, e);
    return sha(canonicalState(st));
  });
  const nodeReplayMs = Math.round(performance.now() - t0);
  const entries = logs.reduce((n, l) => n + l.length, 0);
  const header = { rulesVersion: RULES_VERSION, bundleSha256: sha(code), seed, cases, entries, nodeReplayMs };
  mkdirSync(dirname(vectorsFile), { recursive: true });
  writeFileSync(vectorsFile, [JSON.stringify(header), ...logs.map((l, i) => `${hashes[i]} ${JSON.stringify(l)}`)].join("\n") + "\n");
  Object.assign(summary, { cases, entries, nodeReplayMs });
}
console.log(JSON.stringify(summary));
