// CLI translations (setup, start, doctor, invite). English is the default.
// Language: --lang en|pl, DISCORDRIVE_LANG, the `language` saved in config.json,
// or the first question of `setup`. Keys must match in both dictionaries
// (test/i18n.test.ts); `{name}` placeholders are filled by t().

export type CliLang = "en" | "pl";
export const isCliLang = (x: unknown): x is CliLang => x === "en" || x === "pl";

let current: CliLang = "en";
export const cliLang = (): CliLang => current;
export function setCliLang(l: CliLang): void {
  current = l;
}
/** Language from the environment (flag value first), or null. */
export function envLang(flag?: unknown, env: NodeJS.ProcessEnv = process.env): CliLang | null {
  const v = String(flag ?? env.DISCORDRIVE_LANG ?? "").toLowerCase().slice(0, 2);
  return isCliLang(v) ? v : null;
}

